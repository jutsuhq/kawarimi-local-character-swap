"""Prints the manifest entries for the CUDA runtime asset: NVIDIA's own wheels from PyPI, pinned by version, size and
SHA-256, and the shared libraries to take out of each. Only each wheel's zip directory is read (HTTP range
requests); nothing is downloaded whole.

    python -I scripts/cuda_runtime_pins.py > crates/kawarimi-assets/src/cuda_runtime.rs
"""
import io
import json
import re
import urllib.request
import zipfile

# Versions as ORT 1.2x's CUDA provider needs them (CUDA >= 13.2, cuDNN >= 9.23); the set uv resolved for
# nvidia-cuda-runtime, nvidia-cublas, nvidia-cudnn-cu13, nvidia-cufft, nvidia-curand.
PACKAGES = [
    ("nvidia-cuda-runtime", "13.4.92"),
    ("nvidia-cuda-nvrtc", "13.4.92"),
    ("nvidia-nvjitlink", "13.4.92"),
    ("nvidia-cublas", "13.8.0.4"),
    ("nvidia-cufft", "12.4.0.43"),
    ("nvidia-curand", "10.4.4.72"),
    ("nvidia-cudnn-cu13", "9.27.0.42"),
]
PLATFORMS = {"windows": "win_amd64", "linux": "manylinux_2_27_x86_64"}
# Libraries ORT's CUDA provider and cuDNN load; leaves out the Fortran BLAS shims and cuFFTW.
SKIP = re.compile(r"(nvblas|cufftw)")


class RangeFile(io.RawIOBase):
    """A read-only, seekable file over HTTP range requests."""

    def __init__(self, url, size):
        self.url, self.size, self.pos = url, size, 0

    def seekable(self):
        return True

    def readable(self):
        return True

    def seek(self, offset, whence=0):
        self.pos = {0: offset, 1: self.pos + offset, 2: self.size + offset}[whence]
        return self.pos

    def tell(self):
        return self.pos

    def readinto(self, buffer):
        n = min(len(buffer), self.size - self.pos)
        if n <= 0:
            return 0
        req = urllib.request.Request(self.url, headers={"Range": f"bytes={self.pos}-{self.pos + n - 1}"})
        data = urllib.request.urlopen(req).read()
        buffer[: len(data)] = data
        self.pos += len(data)
        return len(data)


def wheel(package, version, tag):
    info = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{package}/{version}/json"))
    files = [f for f in info["urls"] if f["filename"].endswith(".whl") and tag.split("_")[0] in f["filename"]]
    if tag != "win_amd64":
        files = [f for f in files if "x86_64" in f["filename"] and "manylinux" in f["filename"]]
    if not files:
        raise SystemExit(f"no {tag} wheel for {package} {version}")
    return files[0]


def libraries(url, size, platform):
    names = zipfile.ZipFile(io.BufferedReader(RangeFile(url, size), 1 << 16)).namelist()
    pattern = r"\.dll$" if platform == "windows" else r"\.so(\.\d+)*$"
    return sorted(n for n in names if re.search(pattern, n) and not SKIP.search(n))


def main():
    print("// Generated by scripts/cuda_runtime_pins.py: NVIDIA's CUDA 13 runtime and cuDNN 9 wheels from PyPI.")
    print("use crate::manifest::File;\n")
    for platform, tag in PLATFORMS.items():
        cfg = "windows" if platform == "windows" else "not(windows)"
        print(f"#[cfg({cfg})]")
        print("pub const FILES: &[File] = &[")
        for package, version in PACKAGES:
            f = wheel(package, version, tag)
            libs = libraries(f["url"], f["size"], platform)
            name = package.replace("nvidia-", "")
            print("    File {")
            print(f'        url: "{f["url"]}",')
            print(f'        path: "{name}.zip",')
            print(f'        size: {f["size"]:_},')
            print(f'        sha256: "{f["digests"]["sha256"]}",')
            print("        unpack: &[")
            for lib in libs:
                print(f'            ("{lib}", "{lib.rsplit("/", 1)[1]}"),')
            print("        ],")
            print("    },")
        print("];\n")


if __name__ == "__main__":
    main()
